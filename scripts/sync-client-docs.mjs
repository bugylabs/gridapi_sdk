import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

// The manifest in docs/ is the single source of truth for published SDK metadata.
// Emit a typed TS module into gridapi_client so its docs can render without a
// cross-root import or a tsconfig change.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(path.join(root, "docs/sdk-manifest.json"), "utf8"));
const target = path.resolve(root, "../gridapi_client/src/data/gridapi-sdk-manifest.ts");
writeFileSync(target, `// Generated by gridapi_sdk/scripts/sync-client-docs.mjs — do not edit by hand.\nexport const sdkManifest = ${JSON.stringify(manifest, null, 2)} as const\n`);
console.log(`wrote ${target}`);
